"""mlflow-seed: generate synthetic data, train, evaluate and register the demo systems.

One-shot and idempotent: a case is skipped when every model it registers already has a
``champion`` version tagged with the case's current ``seed_hash``. Afterwards the case folders
(without their answer keys) are copied to ``SEED_CASES_DIR`` for the backend to import.

    python seed.py                  # seed all cases (MLFLOW_TRACKING_URI must be set)
    python seed.py --only SYS-002   # one case
    python seed.py --force          # retrain even when the hash matches
    python seed.py --write-samples  # refresh cases/*/plugins/*/data/sample.csv + stats (no MLflow)
"""

import argparse
import logging
import os
import shutil
import sys
import time
import warnings
from collections.abc import Callable
from pathlib import Path

import pandas as pd
import yaml

from seedlib.registry import is_up_to_date, register_case, seed_hash
from seedlib.spec import CaseResult
from seedlib.systems import sys001, sys002, sys003

ROOT = Path(__file__).resolve().parent
ANSWER_KEY_DIR = "_answer-key"  # never copied into the system folder the agent reads
SAMPLE_ROWS = 30

BUILDERS: dict[str, Callable[..., CaseResult]] = {
    "SYS-001": sys001.build,
    "SYS-002": sys002.build,
    "SYS-003": sys003.build,
}

# Registered model names: a contract with mnamon/model-gateway (docs/services/mlflow.md).
MODEL_NAMES: dict[str, list[str]] = {
    "SYS-001": ["sys-001-cv-parser", "sys-001-cv-ranker"],
    "SYS-002": ["sys-002-credit-scorer"],
    "SYS-003": ["sys-003-benefits-triage"],
}

log = logging.getLogger("mlflow-seed")


def case_dirs(source: Path, only: set[str] | None) -> list[Path]:
    dirs = sorted(p for p in source.iterdir() if p.is_dir() and p.name.startswith("SYS-"))
    return [d for d in dirs if not only or d.name in only]


def seed_case(case_dir: Path, force: bool) -> str:
    builder = BUILDERS.get(case_dir.name)
    if builder is None:
        return "no model (folder only)"
    from mlflow import MlflowClient

    digest = seed_hash(case_dir)
    if not force and is_up_to_date(MlflowClient(), MODEL_NAMES[case_dir.name], digest):
        return f"up to date ({digest[:12]})"
    started = time.monotonic()
    result = builder(case_dir)
    if sorted(m.name for m in result.models) != sorted(MODEL_NAMES[case_dir.name]):
        raise RuntimeError(f"{case_dir.name}: builder models differ from MODEL_NAMES")
    versions = register_case(case_dir, result, digest)
    took = time.monotonic() - started
    return f"registered {versions} in {took:.0f}s ({digest[:12]})"


def export_cases(source: Path, target: Path, dirs: list[Path]) -> None:
    """``target/systems/<SYS>/`` = the dossier; ``target/answer-keys/<SYS>/`` = the key."""
    for case_dir in dirs:
        system = target / "systems" / case_dir.name
        if system.exists():
            shutil.rmtree(system)
        shutil.copytree(case_dir, system, ignore=shutil.ignore_patterns(ANSWER_KEY_DIR))
        key = case_dir / ANSWER_KEY_DIR
        if key.is_dir():
            dest = target / "answer-keys" / case_dir.name
            if dest.exists():
                shutil.rmtree(dest)
            shutil.copytree(key, dest)


def column_stats(frame: pd.DataFrame) -> dict:
    stats: dict = {"rows": len(frame), "columns": {}}
    for name in frame.columns:
        col = frame[name]
        if col.dtype == bool or col.dtype == object or str(col.dtype).startswith(("str", "cat")):
            if col.nunique() > 25:
                stats["columns"][name] = {"distinct": int(col.nunique())}
                continue
            shares = col.astype(str).value_counts(normalize=True).sort_index()
            stats["columns"][name] = {"shares": {k: round(float(v), 3) for k, v in shares.items()}}
        else:
            stats["columns"][name] = {
                "mean": round(float(col.mean()), 3),
                "median": round(float(col.median()), 3),
                "p10": round(float(col.quantile(0.1)), 3),
                "p90": round(float(col.quantile(0.9)), 3),
                "min": round(float(col.min()), 3),
                "max": round(float(col.max()), 3),
            }
    return stats


def write_samples(dirs: list[Path]) -> None:
    for case_dir in dirs:
        builder = BUILDERS.get(case_dir.name)
        if builder is None:
            continue
        for spec in builder(case_dir).models:
            data_dir = case_dir / "plugins" / spec.plugin / "data"
            frame = spec.datasets[0].frame
            frame.head(SAMPLE_ROWS).to_csv(
                data_dir / "sample.csv", index=False, lineterminator="\n"
            )
            header = (
                f"# Generated by `python seed.py --write-samples` from the seed generator\n"
                f"# (dataset {spec.datasets[0].name}). Do not edit by hand.\n"
            )
            body = yaml.safe_dump(column_stats(frame), sort_keys=False, allow_unicode=True)
            (data_dir / "generated-stats.yaml").write_text(header + body, encoding="utf-8")
            log.info("%s: wrote %s sample + stats", case_dir.name, spec.plugin)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", help="comma-separated system ids")
    parser.add_argument("--force", action="store_true", default=os.getenv("SEED_FORCE") == "true")
    parser.add_argument("--write-samples", action="store_true")
    parser.add_argument("--cases", default=os.getenv("SEED_CASES_SRC", str(ROOT / "cases")))
    parser.add_argument("--export", default=os.getenv("SEED_CASES_DIR", ""))
    args = parser.parse_args(argv)

    logging.basicConfig(level=os.getenv("LOG_LEVEL", "INFO"), format="%(levelname)s %(message)s")
    warnings.filterwarnings("ignore", message=".*type hints.*")
    only = set(args.only.split(",")) if args.only else None
    dirs = case_dirs(Path(args.cases), only)

    if args.write_samples:
        write_samples(dirs)
        return 0

    failures = 0
    for case_dir in dirs:
        try:
            log.info("%s: %s", case_dir.name, seed_case(case_dir, args.force))
        except Exception:
            failures += 1
            log.exception("%s: seeding failed", case_dir.name)
    if args.export:
        export_cases(Path(args.cases), Path(args.export), dirs)
        log.info("exported %d case folders to %s", len(dirs), args.export)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
